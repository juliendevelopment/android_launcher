    signingConfigs {
        // Release signing reads from env vars or local properties. When absent we fall back
        // to the debug keystore so CI on tag pushes still produces an installable APK.
        // For Play Store distribution, populate the env vars and uncomment the keystore decode
        // step in .github/workflows/release.yml.
        create("release") {
            val keystorePath = System.getenv("ANDROID_KEYSTORE_PATH")
            if (keystorePath != null && file(keystorePath).exists()) {
                storeFile = file(keystorePath)
                storePassword = System.getenv("KEYSTORE_PASSWORD")
                keyAlias = System.getenv("KEY_ALIAS")
                keyPassword = System.getenv("KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        debug {
            applicationIdSuffix = ".debug"
            versionNameSuffix = "-debug"
        }
        release {
            isMinifyEnabled = false
            isShrinkResources = false
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
            val releaseSigning = signingConfigs.getByName("release")
            signingConfig = if (releaseSigning.storeFile != null) {
                releaseSigning
            } else {
                println("⚠  No release keystore configured; falling back to debug signing.")
                signingConfigs.getByName("debug")
            }
        }
    }

